"""
Visualization Rendering - OVITO-based molecular dynamics visualization.

This module provides functions to render molecular dynamics frames using OVITO
with dynamic script execution generated by the Visualization Agent.
"""

from typing import Dict, Any, Optional
import tempfile
import base64
import os
from ovito_executor import DynamicOVITOExecutor, VisualizationScriptError


def render_frame_to_image_custom(
    data_source,
    ovito_script: Optional[str] = None,
    quality: str = 'medium',
    camera_angle: str = 'default',
    frame_timestep: Optional[int] = None
) -> Optional[str]:
    """
    Render molecular dynamics frames using dynamically generated OVITO scripts.
    
    This function executes LLM-generated OVITO Python scripts to provide flexible,
    customizable visualization based on user requests.
    
    Data source can be:
    - OVITO DataCollection (legacy support)
    - File path to LAMMPS dump file (preferred - loads all properties including c_cna)
    
    IMPORTANT: This function is designed to NEVER raise exceptions that could
    stop the simulation. All errors are caught and logged, with graceful fallback
    to basic visualization or returning None.
    
    Args:
        data_source: Either OVITO DataCollection or file path to LAMMPS dump file
        ovito_script: Optional OVITO Python script string for custom visualization
        quality: Render quality - 'low', 'medium', or 'high' (default: 'medium')
        camera_angle: Camera position - 'default', 'top', or 'side' (default: 'default')
        frame_timestep: Optional timestep to extract from multi-frame dump file
        
    Returns:
        str: Base64-encoded PNG image, or None on error (simulation continues)
    """
    print(f"[RENDER DEBUG] Called with ovito_script: {ovito_script is not None} ({len(ovito_script) if ovito_script else 0} chars)")
    
    try:
        from ovito.pipeline import Pipeline, StaticSource
        from ovito.io import import_file
        from ovito.vis import Viewport, TachyonRenderer
        from ovito.modifiers import ColorCodingModifier
        import platform
        import threading
        
        if data_source is None:
            print("[RENDER] Error: data_source is None")
            return None
        
        # Create pipeline based on data source type
        target_frame_index = 0
        
        if isinstance(data_source, str):
            # File path - use OVITO's native file reader (loads ALL properties including c_cna)
            print(f"[RENDER] Loading dump file: {data_source}")
            pipeline = import_file(data_source)
            
            # If specific timestep requested, find that frame
            if frame_timestep is not None:
                num_frames = pipeline.source.num_frames
                print(f"[RENDER] Searching for timestep {frame_timestep} in {num_frames} frames")
                
                # Find the frame with the matching timestep
                frame_found = False
                for frame_index in range(num_frames):
                    data = pipeline.compute(frame_index)
                    current_timestep = data.attributes.get('Timestep', None)
                    
                    if current_timestep == frame_timestep:
                        print(f"[RENDER] Found timestep {frame_timestep} at frame index {frame_index}")
                        target_frame_index = frame_index
                        frame_found = True
                        break
                
                if not frame_found:
                    print(f"[RENDER] Warning: Timestep {frame_timestep} not found, using frame 0")
                    target_frame_index = 0
        else:
            # DataCollection - legacy support
            print("[RENDER] Using DataCollection (legacy mode)")
            pipeline = Pipeline(source=StaticSource(data=data_source))
        
        # Start each render from a clean modifier stack to avoid per-frame accumulation
        pipeline.modifiers.clear()

        if ovito_script:
            # Execute custom OVITO script
            print(f"[RENDER] Executing custom OVITO script ({len(ovito_script)} chars)")
            try:
                executor = DynamicOVITOExecutor()
                data = pipeline.compute(target_frame_index)
                pipeline = executor.execute_script(ovito_script, pipeline, data)
                print("[RENDER] Custom OVITO script executed successfully")
                
            except VisualizationScriptError as e:
                print(f"[RENDER] Script execution failed: {e}")
                print("[RENDER] Falling back to default visualization")
                apply_basic_visualization(pipeline)
                
            except Exception as e:
                print(f"[RENDER] Unexpected error: {type(e).__name__}: {e}")
                print("[RENDER] Falling back to default visualization")
                apply_basic_visualization(pipeline)
        else:
            # No custom script - use default visualization
            print("[RENDER] Using default visualization")
            apply_basic_visualization(pipeline)
        
        # Add pipeline to scene (docs/ovito_docs/pipelines.md)
        pipeline.add_to_scene()
        
        # Create viewport for rendering
        viewport = Viewport()
        viewport.type = Viewport.Type.Perspective
        
        if camera_angle == 'top':
            viewport.camera_pos = (0, 0, 50)
            viewport.camera_dir = (0, 0, -1)
        elif camera_angle == 'side':
            viewport.camera_pos = (50, 0, 0)
            viewport.camera_dir = (-1, 0, 0)
        else:  # default perspective
            viewport.camera_pos = (30, 30, 30)
            viewport.camera_dir = (-1, -1, -1)
        
        if quality == 'high':
            render_size = (800, 600)
        elif quality == 'low':
            render_size = (400, 300)
        else:  # medium
            render_size = (600, 450)
        
        # Zoom to fit all particles
        viewport.zoom_all()
        
        # Render to temporary file
        with tempfile.NamedTemporaryFile(suffix='.png', delete=False) as tmp_file:
            tmp_path = tmp_file.name
        
        try:
            # Use TachyonRenderer for thread safety (especially on macOS)
            renderer = TachyonRenderer()
            renderer.antialiasing = True
            renderer.direct_light_intensity = 0.9
            renderer.shadows = True
            renderer.ambient_occlusion = True
            renderer.depth_of_field = False
            
            # Check threading context
            is_main_thread = threading.current_thread() is threading.main_thread()
            is_macos = platform.system() == 'Darwin'
            
            if not is_main_thread and is_macos:
                print("Non-main thread on macOS - using TachyonRenderer")
            
            # Render the image (specify the frame to render)
            viewport.render_image(
                filename=tmp_path,
                size=render_size,
                alpha=True,
                renderer=renderer,
                frame=target_frame_index
            )
            
            # Read and encode as base64
            with open(tmp_path, 'rb') as img_file:
                img_data = img_file.read()
                base64_image = base64.b64encode(img_data).decode('utf-8')
            
            return base64_image
            
        finally:
            # Clean up temporary file
            if os.path.exists(tmp_path):
                os.unlink(tmp_path)
            # Remove pipeline from scene so subsequent frames start clean
            pipeline.remove_from_scene()
    
    except Exception as e:
        print(f"Error rendering frame: {e}")
        import traceback
        print(f"Full traceback: {traceback.format_exc()}")
        return None


def apply_basic_visualization(pipeline) -> None:
    """
    Apply basic visualization as fallback when no custom script is provided
    or when script execution fails.
    
    This provides simple particle type coloring to ensure frames are always
    rendered even if custom visualization fails.
    
    Args:
        pipeline: OVITO Pipeline to modify
    """
    from ovito.modifiers import ColorCodingModifier
    
    print("[RENDER] Applying basic particle type coloring")
    # Simple color coding by particle type
    color_modifier = ColorCodingModifier(
        property='Particle Type',
        gradient=ColorCodingModifier.Hot()
    )
    pipeline.modifiers.append(color_modifier)
